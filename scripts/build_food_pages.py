def load_items(code, lc, skipped):
    items = []
    def add(base, name, label, f, group, source=None, slug=None):
        name = re.sub(r"\s*\(([^)]*)\)\s*$", lambda m: "" if m.group(1).strip().lower() == label.strip().lower() else m.group(0), name).strip()
        items.append(dict(base=base, name=name, label=label, grams=f["servingGrams"], kcal=f["kcal"], p=f["protein"], c=f["carbs"],
                          fat=f["fat"], group=group, source=source, slug=slug))
    if lc.get("data_file"):
        for f in json.load(open(os.path.join(SITE, "data/foods/%s.json" % code), encoding="utf-8"))["foods"]:
            add(f["name"], f["displayName"], f["servingLabel"], f, f["group"], f.get("source"), f.get("slug"))
        return items
    loc = lc["loc"]
    if lc.get("tr_pick"):
        by = {f["name"]: f for f in jload("tr_home_foods.json")}
        for n in TR_PICK:
            add(n, tr_sentence(n), by[n]["servingLabel"], by[n], "local")
    else:
        for f in jload("foods_cuisines.json"):
            if f["cuisine"] in lc["cuisines"]:
                nm, lb = f["localizedNames"].get(loc), f["localizedServingLabels"].get(loc)
                if nm and lb: add(f["name"], nm, lb, f, "local")
                else: skipped.append((code, f["name"], "missing localized name/label"))
    for f in jload("foods_international.json"):
        nm, lb = f["localizedNames"].get(loc), f["localizedServingLabels"].get(loc)
        if nm and lb: add(f["name"], tr_sentence(nm) if code == "tr" else nm, lb, f, "staple")
        else: skipped.append((code, f["name"], "missing localized name/label"))
    return items


def inline_name(code, name):
    if code == "en": return en_inline(name)
    if code in ("es", "pt-BR"): return name[0].lower() + name[1:]
    return name


