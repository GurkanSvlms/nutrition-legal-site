# ---------------------------------------------------------------- checks
def check(data, written):
    errs = []
    paths = {w[0] for w in written}
    for path, url, code, it in written:
        txt = open(path, encoding="utf-8").read()
        for m in re.findall(r'<script type="application/ld\+json">\s*(.*?)\s*</script>', txt, re.S):
            try: json.loads(m)
            except Exception as ex: errs.append("bad ld+json %s: %s" % (path, ex))
        for ref in re.findall(r'(?:href|src)="([^"]+)"', txt):
            if re.match(r"(https?:|mailto:|#)", ref): continue
            t = ref.split("#")[0].split("?")[0]
            t = os.path.normpath(os.path.join(os.path.dirname(path), t))
            if os.path.isdir(t): t = os.path.join(t, "index.html")
            if not os.path.exists(t): errs.append("broken link %s -> %s" % (path, ref))
        if it:
            ld = json.loads(re.search(r'<script type="application/ld\+json">\s*(.*?)\s*</script>', txt, re.S).group(1))
            nut = ld["@graph"][0]["mainEntity"]["nutrition"]
            g = float(nut["servingSize"].split()[0])
            rows = re.findall(r"<tr><th scope=\"row\">[^<]*</th><td>([^<]*)</td><td>([^<]*)</td></tr>", txt)
            vals = [(float(a.split()[0].replace(",", ".")), float(b.split()[0].replace(",", "."))) for a, b in rows]
            src = [it["kcal"], it["p"], it["c"], it["fat"]]
            for (s, p100), raw, tol in zip(vals, src, (0.51, 0.06, 0.06, 0.06)):
                if abs(s - raw) > 1e-9 or abs(p100 - raw / g * 100) > tol: errs.append("math %s: %s %s %s g=%s" % (path, s, p100, raw, g))
            if nut["calories"] != "%s kcal" % it["kcal"]: errs.append("ld kcal mismatch " + path)
    for code, items in data.items():  # unique slugs + hub links every page
        slugs = [i["slug"] for i in items]
        if len(slugs) != len(set(slugs)): errs.append("dup slugs " + code)
        hub = open(os.path.join(SITE, LANGS[code]["dir"], "index.html"), encoding="utf-8").read()
        for i in items:
            if 'href="%s.html"' % i["slug"] not in hub: errs.append("hub %s missing %s" % (code, i["slug"]))
    # hreflang reciprocity: same set on every page of a group
    sets = {}
    for path, url, code, it in written:
        txt = open(path, encoding="utf-8").read()
        sets.setdefault(it["base"] if it else "hub", []).append(frozenset(re.findall(r'hreflang="([^"]+)" href="([^"]+)"', txt)))
    for k, v in sets.items():
        if len(set(v)) != 1: errs.append("hreflang sets differ for " + k)
    return errs


